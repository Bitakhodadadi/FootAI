# پروژه مدرسه‌ای FootAI
# برنامه ساده برای بررسی آمار یک بازیکن فوتبال

print("================================")
print("      FootAI - دستیار فوتبال")
print("================================")

# دریافت اطلاعات بازیکن
name = input("نام بازیکن را وارد کنید: ")
position = input("پست بازیکن (مثلاً هافبک): ")

# دریافت آمار مسابقه
correct_passes = int(input("تعداد پاس‌های صحیح: "))
wrong_passes = int(input("تعداد پاس‌های اشتباه: "))
shots = int(input("تعداد شوت‌ها: "))
lost_balls = int(input("تعداد دفعات از دست دادن توپ: "))

# محاسبه تعداد کل پاس‌ها و دقت پاس
total_passes = correct_passes + wrong_passes

if total_passes > 0:
    accuracy = correct_passes / total_passes * 100
else:
    accuracy = 0

# نمایش گزارش بازیکن
print("\n---------- گزارش بازیکن ----------")
print("نام:", name)
print("پست:", position)
print("دقت پاس:", round(accuracy), "درصد")

# بررسی ساده عملکرد بازیکن
print("\nنقاط قوت و پیشنهادها:")

if accuracy >= 80:
    print("- دقت پاس خوبی داری.")
else:
    print("- برای بهتر شدن، پاس دادن را بیشتر تمرین کن.")

if shots >= 3:
    print("- در مسابقه شوت‌های زیادی زدی.")
else:
    print("- می‌توانی فرصت‌های بیشتری برای شوت پیدا کنی.")

if lost_balls >= 5:
    print("- بهتر است روی کنترل توپ تمرین کنی.")
else:
    print("- تعداد دفعات از دست دادن توپ کم بوده است.")

# پیشنهاد کلی برای جای‌گیری
print("\nپیشنهاد جای‌گیری:")
if position == "هافبک":
    print("فضای خالی را پیدا کن و در زاویه مناسب برای دریافت پاس قرار بگیر.")
elif position == "مهاجم":
    print("فضای خالی پشت مدافعان را بررسی کن و برای دریافت پاس حرکت کن.")
elif position == "مدافع":
    print("بین بازیکن حریف و دروازه خودی قرار بگیر و با هم‌تیمی‌ها هماهنگ باش.")
else:
    print("جای خود را با توجه به توپ و دستور مربی تنظیم کن.")

print("\nاین برنامه آموزشی است؛ برای تصمیم‌گیری در مسابقه به دستور مربی هم توجه کن.")
print("پایان برنامه - موفق باشی!")
